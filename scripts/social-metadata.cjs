const fs = require("node:fs");
const path = require("node:path");
const sharp = require("sharp");

const root = path.resolve(__dirname, "..");
const configPath = path.join(root, "content", "social-pages.json");
const imageDirectory = path.join(root, "assets", "img", "social");
const checkOnly = process.argv.includes("--check");
const excludedFiles = ["404.html", "impressum.html", "datenschutz.html"];

function fail(message) {
  throw new Error(message);
}

function escapeXml(value) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&apos;");
}

function extractOne(html, expression, label, file) {
  const matches = [...html.matchAll(expression)];
  if (matches.length !== 1) fail(`${file} must contain exactly one ${label}`);
  return matches[0][1].trim();
}

function pageMetadata(html, file) {
  const title = extractOne(html, /<title>([^<]+)<\/title>/gi, "title", file);
  const description = extractOne(
    html,
    /<meta\s+name=["']description["']\s+content=["']([^"']+)["']\s*\/?\s*>/gi,
    "meta description",
    file
  );
  const canonical = extractOne(
    html,
    /<link\s+rel=["']canonical["']\s+href=["']([^"']+)["']\s*\/?\s*>/gi,
    "canonical",
    file
  );
  const socialTitle = title
    .replace(/\s+\|\s+(?:yorck\. consulting|Yorck Consulting)$/i, "")
    .replace(/\s+—\s+yorck\. consulting$/i, "");
  return { title, socialTitle, description, canonical };
}

function socialBlock(config, page, metadata) {
  const imageUrl = `${config.origin}/assets/img/social/${page.image}`;
  const values = {
    type: page.type,
    locale: config.locale,
    siteName: config.siteName,
    title: metadata.socialTitle,
    description: metadata.description,
    canonical: metadata.canonical,
    imageUrl,
    imageAlt: page.imageAlt
  };
  for (const [name, value] of Object.entries(values)) {
    if (!value || typeof value !== "string") fail(`${page.file} has an invalid social value: ${name}`);
  }
  const escaped = Object.fromEntries(Object.entries(values).map(([name, value]) => [name, escapeXml(value)]));
  return [
    "  <!-- social:start — generated by npm run social:sync -->",
    `  <meta property="og:type" content="${escaped.type}">`,
    `  <meta property="og:locale" content="${escaped.locale}">`,
    `  <meta property="og:site_name" content="${escaped.siteName}">`,
    `  <meta property="og:title" content="${escaped.title}">`,
    `  <meta property="og:description" content="${escaped.description}">`,
    `  <meta property="og:url" content="${escaped.canonical}">`,
    `  <meta property="og:image" content="${escaped.imageUrl}">`,
    `  <meta property="og:image:secure_url" content="${escaped.imageUrl}">`,
    "  <meta property=" + '"og:image:type" content="image/png">',
    "  <meta property=" + '"og:image:width" content="1200">',
    "  <meta property=" + '"og:image:height" content="630">',
    `  <meta property="og:image:alt" content="${escaped.imageAlt}">`,
    "  <meta name=" + '"twitter:card" content="summary_large_image">',
    `  <meta name="twitter:title" content="${escaped.title}">`,
    `  <meta name="twitter:description" content="${escaped.description}">`,
    `  <meta name="twitter:image" content="${escaped.imageUrl}">`,
    `  <meta name="twitter:image:alt" content="${escaped.imageAlt}">`,
    "  <!-- social:end -->"
  ].join("\n");
}

function withSocialBlock(html, block, file) {
  let clean = html.replace(/^[ \t]*<!-- social:start[\s\S]*?^[ \t]*<!-- social:end -->[ \t]*\r?\n?/gim, "");
  clean = clean.replace(
    /^[ \t]*<meta\s+(?:property=["']og:[^"']+["']|name=["']twitter:[^"']+["'])[^>]*>[ \t]*\r?\n?/gim,
    ""
  );
  const headEnd = clean.indexOf("</head>");
  if (headEnd === -1) fail(`${file} has no closing head tag`);
  clean = clean.slice(0, headEnd)
    .replace(/^<link\s+rel=["']preload["']/gim, "  <link rel=\"preload\"")
    .replace(/\n{3,}/g, "\n\n") + clean.slice(headEnd);
  const canonical = [...clean.matchAll(/<link\s+rel=["']canonical["']\s+href=["'][^"']+["']\s*\/?\s*>/gi)];
  if (canonical.length !== 1) fail(`${file} must contain exactly one canonical before social metadata can be inserted`);
  return clean.replace(canonical[0][0], `${canonical[0][0]}\n${block}`);
}

function wrapTitle(title) {
  const upper = title.toLocaleUpperCase("de-DE");
  const words = upper.split(/\s+/);
  const baseSize = upper.length <= 30 ? 82 : upper.length <= 48 ? 70 : upper.length <= 68 ? 58 : 50;
  const longestWord = Math.max(...words.map((word) => word.length));
  let fontSize = Math.min(baseSize, Math.floor(900 / (longestWord * 0.65)));
  let lines;
  do {
    const maxCharacters = Math.floor(860 / (fontSize * 0.65));
    lines = [];
    let current = "";
    for (const word of words) {
      const candidate = current ? `${current} ${word}` : word;
      if (candidate.length <= maxCharacters || !current) current = candidate;
      else {
        lines.push(current);
        current = word;
      }
    }
    if (current) lines.push(current);
    if (lines.length > 3) fontSize -= 2;
  } while (lines.length > 3 && fontSize >= 40);
  if (lines.length > 3) fail(`Social card title needs more than three lines: ${title}`);
  return { fontSize, lines };
}

async function cardBuffer(config, page, metadata) {
  if (!/^#[0-9a-f]{6}$/i.test(page.accent)) fail(`${page.file} has an invalid accent color`);
  const display = wrapTitle(metadata.socialTitle);
  const lineHeight = Math.round(display.fontSize * 0.98);
  const firstBaseline = 222 - Math.max(0, display.lines.length - 2) * 15;
  const font = fs.readFileSync(path.join(root, "assets", "fonts", "leaguespartan-800.woff2")).toString("base64");
  const titleLines = display.lines.map((line, index) => (
    `<text x="82" y="${firstBaseline + index * lineHeight}" class="title">${escapeXml(line)}</text>`
  )).join("");
  const svg = `
    <svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
      <style>
        @font-face { font-family: "League Spartan"; src: url("data:font/woff2;base64,${font}") format("woff2"); font-weight: 800; }
        text { font-family: "League Spartan", Arial, sans-serif; }
        .title { fill: #ffffff; font-size: ${display.fontSize}px; font-weight: 800; letter-spacing: -1px; }
        .label { fill: ${page.accent}; font-size: 26px; font-weight: 800; letter-spacing: 5px; }
        .site { fill: #ffffff; font-size: 25px; font-weight: 800; letter-spacing: 1px; }
        .url { fill: #bdbdbd; font-size: 20px; font-weight: 800; letter-spacing: 1px; }
      </style>
      <rect width="1200" height="630" fill="#000000"/>
      <rect width="22" height="630" fill="${page.accent}"/>
      <rect x="1030" y="0" width="170" height="200" fill="${page.accent}"/>
      <circle cx="1094" cy="486" r="118" fill="${page.accent}" opacity="0.16"/>
      <text x="82" y="105" class="label">${escapeXml(page.category.toLocaleUpperCase("de-DE"))}</text>
      ${titleLines}
      <rect x="82" y="472" width="180" height="7" fill="${page.accent}"/>
      <text x="82" y="560" class="site">YORCK. CONSULTING</text>
      <text x="1118" y="560" text-anchor="end" class="url">YORCK-CONSULTING.COM</text>
    </svg>`;
  return sharp(Buffer.from(svg)).png({ compressionLevel: 9, adaptiveFiltering: false }).toBuffer();
}

function sitemapPaths(config) {
  const sitemap = fs.readFileSync(path.join(root, "sitemap.xml"), "utf8");
  return [...sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)].map((match) => {
    const url = new URL(match[1]);
    if (url.origin !== config.origin) fail(`Sitemap contains a foreign origin: ${match[1]}`);
    return url.pathname;
  });
}

function validateRegistry(config) {
  if (!config || !Array.isArray(config.pages) || !config.pages.length) fail("Social page registry is empty");
  const fields = ["file", "path", "type", "category", "accent", "image", "imageAlt"];
  for (const page of config.pages) {
    for (const field of fields) if (!page[field]) fail(`Social registry entry is missing ${field}`);
    if (!page.image.endsWith(".png") || path.basename(page.image) !== page.image) fail(`${page.file} has an invalid image name`);
    if (!["website", "article"].includes(page.type)) fail(`${page.file} has an invalid Open Graph type`);
  }
  for (const field of ["file", "path", "image"]) {
    const values = config.pages.map((page) => page[field]);
    if (new Set(values).size !== values.length) fail(`Social registry contains a duplicate ${field}`);
  }
  const registered = config.pages.map((page) => page.path).sort();
  const sitemap = sitemapPaths(config).sort();
  if (JSON.stringify(registered) !== JSON.stringify(sitemap)) fail("Social registry must match all and only sitemap URLs");
}

async function main() {
  const config = JSON.parse(fs.readFileSync(configPath, "utf8"));
  validateRegistry(config);
  const stale = [];
  const expectedImages = new Set(config.pages.map((page) => page.image));
  if (!checkOnly) fs.mkdirSync(imageDirectory, { recursive: true });

  for (const page of config.pages) {
    const file = path.join(root, page.file);
    if (!fs.existsSync(file)) fail(`Missing public page: ${page.file}`);
    const html = fs.readFileSync(file, "utf8");
    if (/name=["']robots["']\s+content=["'][^"']*noindex/i.test(html)) fail(`${page.file} is public but marked noindex`);
    const metadata = pageMetadata(html, page.file);
    if (metadata.canonical !== config.origin + page.path) fail(`${page.file} canonical does not match its registered path`);
    const expectedHtml = withSocialBlock(html, socialBlock(config, page, metadata), page.file);
    const expectedCard = await cardBuffer(config, page, metadata);
    const imageFile = path.join(imageDirectory, page.image);

    if (checkOnly) {
      if (html !== expectedHtml) stale.push(`${page.file}: social metadata is stale`);
      if (!fs.existsSync(imageFile) || !fs.readFileSync(imageFile).equals(expectedCard)) {
        stale.push(`assets/img/social/${page.image}: social card is stale`);
      }
    } else {
      if (html !== expectedHtml) fs.writeFileSync(file, expectedHtml);
      if (!fs.existsSync(imageFile) || !fs.readFileSync(imageFile).equals(expectedCard)) fs.writeFileSync(imageFile, expectedCard);
    }
  }

  for (const file of excludedFiles) {
    const html = fs.readFileSync(path.join(root, file), "utf8");
    if (/(?:property=["']og:|name=["']twitter:)/i.test(html)) fail(`${file} must not contain social metadata`);
  }

  if (fs.existsSync(imageDirectory)) {
    for (const filename of fs.readdirSync(imageDirectory)) {
      if (filename.endsWith(".png") && !expectedImages.has(filename)) {
        if (checkOnly) stale.push(`assets/img/social/${filename}: unregistered generated card`);
        else fs.rmSync(path.join(imageDirectory, filename));
      }
    }
  }

  if (stale.length) {
    console.error(stale.map((item) => `- ${item}`).join("\n"));
    console.error("Run npm run social:sync and review the generated changes.");
    process.exitCode = 1;
    return;
  }
  console.log(checkOnly ? "Social metadata and cards are current." : `Synchronized ${config.pages.length} social metadata sets and cards.`);
}

main().catch((error) => {
  console.error(error.stack || error.message);
  process.exitCode = 1;
});
